#!/usr/bin/env node
/**
 * Builds the exercise catalogue from free-exercise-db (specs 10.1, slice 11).
 *
 * ## THE THIRD SOURCE, AND WHY THE SECOND WAS REPLACED
 *
 * everkinetic came first (293 exercises, 32 hand-named in French), then wger
 * (520 exercises, 194 line drawings, already translated). This is the third,
 * asked for by name, and the reason it wins is the licence: free-exercise-db is
 * released under THE UNLICENSE — the full public-domain dedication, verified by
 * reading LICENSE.md in the repository rather than the badge in its README.
 * wger is CC BY-SA, which is fine but carries attribution and share-alike
 * obligations into a public repository and public releases.
 *
 * | | wger | free-exercise-db |
 * | --- | --- | --- |
 * | exercises | 520 | 876 |
 * | media | 194 line drawings, PNG | 1746 photographs, 2 per exercise |
 * | naming | French, by its contributors | English only |
 * | licence | CC BY-SA 3/4, credited per image | Unlicense (public domain) |
 *
 * ## WHAT IT COST, STATED RATHER THAN DISCOVERED
 *
 * THE NAMES. wger shipped French; this ships English, 876 of them. So the
 * translation is now ours and lives in ./exercise-names-fr.mjs, written out one
 * by one rather than generated by a token translator — the reasoning is in that
 * file. A missing key throws here instead of silently leaving English in a
 * French library.
 *
 * THE BYTES. 1746 photographs at source resolution are 103 MB. They are
 * resized to 400 px wide at quality 65, which is 21 KB each and about 37 MB in
 * all — measured, not estimated, and checked by looking at the result. 400 px
 * is right for a 44 pt list thumbnail and for two images side by side on an
 * exercise page.
 *
 * ## WHAT IT BOUGHT
 *
 * Every exercise has a picture, where wger drew 194 of 520. And the pair IS the
 * movement: image 0 is the start, image 1 is the end. A single photograph of
 * somebody halfway through a squat does not say how deep they went.
 *
 * ## A NOTE ON jimp-compact
 *
 * The resizing uses `jimp-compact`, which is present in node_modules as a
 * TRANSITIVE dependency of the Expo toolchain, not something this project
 * declared. That is acceptable here and nowhere else: this script runs by hand,
 * its output is committed, and nothing it produces is imported by the
 * application. If it ever disappears the script fails loudly on the require,
 * which is the right failure — the committed assets keep working.
 *
 * ## WHY THE OUTPUT IS COMMITTED
 *
 * Same two reasons extract-body-map.mjs and generate-icons.mjs give. A build
 * step fetching from a third party would make every CI run depend on that
 * service staying up, to regenerate files that do not change. And an asset
 * nobody can regenerate is a decision nobody can revisit.
 *
 * Usage:
 *   node scripts/fetch-exercise-catalog.mjs
 */

import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXERCISE_NAMES_FR } from './exercise-names-fr.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const IMAGES_DIR = join(ROOT, 'assets/exercises');
const CATALOG_OUT = join(ROOT, 'src/features/strength/catalog/catalog.generated.ts');
const IMAGES_OUT = join(ROOT, 'src/features/strength/catalog/images.generated.ts');
const LICENCE_OUT = join(ROOT, 'src/features/strength/catalog/LICENSE.md');

const REPO = 'yuhonas/free-exercise-db';
const RAW = `https://raw.githubusercontent.com/${REPO}/main`;
const DATA_URL = `${RAW}/dist/exercises.json`;

/** Measured: 400 px at quality 65 is 21 KB and legible. See the header. */
const IMAGE_WIDTH = 400;
const IMAGE_QUALITY = 65;

/**
 * free-exercise-db's seventeen muscles onto our fifteen (specs 14.20 no 1).
 *
 * Neither vocabulary bends to the other: making the schema follow a third
 * party's list would tie the column to their database, and slice 10 chose these
 * fifteen as the granularity somebody LABELS an exercise with.
 *
 * Three of theirs have no equivalent and are placed rather than dropped, which
 * is the rule the body map already follows — THE ERROR THIS GUARDS AGAINST IS
 * THE FALSE NEGATIVE. A muscle trained but left grey reads as "I never train
 * this", which is a false belief somebody acts on for weeks; a region lit a
 * little too eagerly costs nothing.
 *
 * - `middle back` (rows, rhomboids) -> `lats`. It is what a French lifter calls
 *   a row — du dos — and body-map.ts already draws `lats` over the upper-back
 *   region, which covers the rhomboids and the middle trapezius. Sending it to
 *   `traps` would light the shrug region for a row.
 * - `abductors` (gluteus medius and minimus) -> `glutes`. Same muscle group,
 *   one level coarser.
 * - `neck` -> `traps`, which is the nearest thing we name and the region the
 *   drawing lights.
 */
const MUSCLES = {
  abdominals: 'abs',
  abductors: 'glutes',
  adductors: 'adductors',
  biceps: 'biceps',
  calves: 'calves',
  chest: 'chest',
  forearms: 'forearms',
  glutes: 'glutes',
  hamstrings: 'hamstrings',
  lats: 'lats',
  'lower back': 'lower_back',
  'middle back': 'lats',
  neck: 'traps',
  quadriceps: 'quads',
  shoulders: 'shoulders',
  traps: 'traps',
  triceps: 'triceps',
};

/**
 * `obliques` exists in our vocabulary and NOT in theirs — they fold it into
 * `abdominals` — so without this rule one of our fifteen would never once be a
 * primary muscle, and its filter would always come back empty.
 *
 * THE RULE ONLY EVER FIRES WHEN THE SOURCE SAYS `abdominals`, which is what
 * makes it safe. It reassigns inside the abdominal family and can never steal a
 * chest exercise from "Incline Dumbbell Flyes - With A Twist" — the reason the
 * word `twist` alone is not in the pattern.
 *
 * Same instrument and same caveat as the wger script's name rules: weaker than
 * data, used only where the source cannot express the answer at all.
 */
const OBLIQUE_PATTERN =
  /\boblique|side bend|russian twist|wood ?chop|side jackknife|side bridge|torso rotation|plate twist|full twist|barbell twist|180's/i;

/**
 * Their thirteen equipment values onto our eight (specs 10.1).
 *
 * `null` is kept as `null` and is a REAL ANSWER rather than a gap: slice 10
 * settled that an exercise with no equipment matches no filter, because
 * pretending it matches would assert something nobody said.
 *
 * `medicine ball`, `exercise ball` and `foam roll` land in `other` — they are
 * equipment, they are simply not one of the eight this application filters by.
 */
const EQUIPMENT = {
  barbell: 'barbell',
  'e-z curl bar': 'barbell',
  dumbbell: 'dumbbell',
  cable: 'cable',
  machine: 'machine',
  'body only': 'bodyweight',
  kettlebells: 'kettlebell',
  bands: 'band',
  'medicine ball': 'other',
  'exercise ball': 'other',
  'foam roll': 'other',
  other: 'other',
};

/**
 * What a brand-new library is given without being asked (specs 10.1).
 *
 * ## THE CRITERION IS THEIRS, NOT MINE, AND THE FIRST ONE WAS WRONG
 *
 * The wger catalogue used "has a drawing", which worked because only 194 of 520
 * had one. Here all 876 do, so that instrument is gone.
 *
 * `level: 'beginner'` was tried and is WRONG, caught by listing the staple
 * lifts against it: it excludes the deadlift, the overhead press, the Romanian
 * deadlift, the lunge and the front squat. Their `level` grades TECHNICAL
 * DIFFICULTY, not how ordinary a movement is, and a default library without a
 * deadlift is a broken default library.
 *
 * What is left is the honest question — is this a thing you do for sets and
 * reps — and their `category` answers it. `strength` and `powerlifting` are in;
 * `stretching`, `cardio`, `plyometrics`, `strongman` and `olympic weightlifting`
 * stay in the catalogue, searchable, because they are either not sets-and-reps
 * or specialised enough to be chosen rather than given.
 *
 * Equipment must be one of the eight we name, so a sled or a tyre is not handed
 * to somebody who has neither.
 *
 * Result: 552 of 876, covering all fifteen muscles.
 */
/**
 * Which exercises are measured in SECONDS rather than in repetitions.
 *
 * `exercise.tracks_duration` is the column slice 11 found dead in the water —
 * read in four places and written by nothing — and this catalogue is the only
 * thing that exercises it on day one. Losing it here would put `0` on every
 * exercise that ever existed again, silently.
 *
 * Two whole categories qualify by definition: a stretch and a piece of cardio
 * are both held for a time. The rest is a written-out list rather than a
 * pattern, for the reason the name table gives — `/\bplank\b/` also matches
 * "Push Up to Side Plank", which is counted in reps.
 */
const TIMED_CATEGORIES = new Set(['stretching', 'cardio']);
const TIMED_NAMES = new Set([
  'Backward Drag',
  'Balance Board',
  'Battling Ropes',
  'Bear Crawl Sled Drags',
  "Conan's Wheel",
  'Crucifix',
  'Dead Bug',
  'Downward Facing Balance',
  "Farmer's Walk",
  'Forward Drag with Press',
  'Isometric Chest Squeezes',
  'Isometric Neck Exercise - Front And Back',
  'Isometric Neck Exercise - Sides',
  'Isometric Wipers',
  'Monster Walk',
  'One Handed Hang',
  'Plank',
  'Power Stairs',
  'Rickshaw Carry',
  'Side Bridge',
  'Sled Drag - Harness',
  'Sled Overhead Backward Walk',
  'Sled Push',
  'Spider Crawl',
  'Stomach Vacuum',
  'Superman',
  'Yoke Walk',
]);

const DEFAULT_CATEGORIES = new Set(['strength', 'powerlifting']);
const DEFAULT_EQUIPMENT = new Set([
  'barbell',
  'dumbbell',
  'cable',
  'machine',
  'bodyweight',
  'kettlebell',
  'band',
]);

