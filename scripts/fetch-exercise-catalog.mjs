/** A URL-safe, dump-readable key derived from the French name. */
function slugify(name) {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/['’]/g, '-')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-');
}

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

async function fetchImage(path) {
  // The source stores files under names containing spaces and parentheses.
  const url = `${RAW}/exercises/${path.split('/').map(encodeURIComponent).join('/')}`;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
      return Buffer.from(await res.arrayBuffer());
    } catch (error) {
      if (attempt === 2) throw new Error(`${url}: ${error.message}`);
      await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
    }
  }
  throw new Error('unreachable');
}

async function shrink(buffer) {
  const image = await Jimp.read(buffer);
  return image.resize(IMAGE_WIDTH, Jimp.AUTO).quality(IMAGE_QUALITY).getBufferAsync(Jimp.MIME_JPEG);
}

/** Runs `worker` over `items` with a bounded number in flight. */
async function pooled(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  const runners = Array.from({ length: limit }, async () => {
    for (;;) {
      const index = next;
      next += 1;
      if (index >= items.length) return;
      results[index] = await worker(items[index], index);
    }
  });
  await Promise.all(runners);
  return results;
}

function frenchName(englishName) {
  const french = EXERCISE_NAMES_FR[englishName];
  if (french === undefined) {
    throw new Error(
      `No French name for "${englishName}". Add it to scripts/exercise-names-fr.mjs — ` +
        'an English name must never reach a French library.',
    );
  }
  return french;
}

function musclesOf(entry) {
  const primaryRaw = entry.primaryMuscles?.[0];
  if (primaryRaw === undefined) return null;
  const primary = MUSCLES[primaryRaw];
  if (primary === undefined) throw new Error(`Unmapped muscle "${primaryRaw}"`);

  const secondary = [];
  for (const raw of entry.secondaryMuscles ?? []) {
    const mapped = MUSCLES[raw];
    if (mapped === undefined) throw new Error(`Unmapped muscle "${raw}"`);
    if (mapped !== primary && !secondary.includes(mapped)) secondary.push(mapped);
  }

  // See OBLIQUE_PATTERN: only ever inside the abdominal family.
  if (primaryRaw === 'abdominals' && OBLIQUE_PATTERN.test(entry.name)) {
    return { primary: 'obliques', secondary: secondary.filter((m) => m !== 'obliques') };
  }
  return { primary, secondary };
}

function equipmentOf(entry) {
  if (entry.equipment === null || entry.equipment === undefined) return null;
  const mapped = EQUIPMENT[entry.equipment];
  if (mapped === undefined) throw new Error(`Unmapped equipment "${entry.equipment}"`);
  return mapped;
}

async function main() {
  console.log(`Fetching ${DATA_URL} …`);
  const raw = await fetchJson(DATA_URL);
  console.log(`  ${raw.length} exercises`);

  const entries = [];
  const seenKeys = new Map();

  for (const item of raw) {
    const muscles = musclesOf(item);
    if (muscles === null) continue; // No muscle at all: nothing to file it under.

    const name = frenchName(item.name);
    const key = slugify(name);
    if (seenKeys.has(key)) {
      throw new Error(`Key "${key}" collides: "${seenKeys.get(key)}" and "${item.name}"`);
    }
    seenKeys.set(key, item.name);

    const equipment = equipmentOf(item);
    entries.push({
      key,
      name,
      primaryMuscle: muscles.primary,
      secondaryMuscles: muscles.secondary,
      equipment,
      tracksDuration: TIMED_CATEGORIES.has(item.category) || TIMED_NAMES.has(item.name),
      images: item.images ?? [],
      isDefault:
        DEFAULT_CATEGORIES.has(item.category) &&
        equipment !== null &&
        DEFAULT_EQUIPMENT.has(equipment) &&
        (item.images ?? []).length > 0,
    });
  }

  entries.sort((a, b) => a.name.localeCompare(b.name, 'fr'));
  console.log(`  ${entries.length} kept, ${entries.filter((e) => e.isDefault).length} in the default set`);

  // --- images -------------------------------------------------------------

  // KEEP is for re-running the generator after a catalogue change without
  // spending twenty minutes and 1746 requests on images that have not moved.
  // The default is still a clean wipe, so a stale file can never survive a
  // rename: it would otherwise sit in assets/ referenced by nothing.
  const keepImages = process.env.KEEP_IMAGES === '1';
  if (!keepImages) rmSync(IMAGES_DIR, { recursive: true, force: true });
  mkdirSync(IMAGES_DIR, { recursive: true });

  const jobs = [];
  for (const entry of entries) {
    entry.imageFiles = [];
    entry.images.forEach((path, index) => {
      const file = `${entry.key}-${index + 1}.jpg`;
      entry.imageFiles.push(file);
      jobs.push({ path, file });
    });
  }

  console.log(`Downloading and resizing ${jobs.length} images …`);
  let done = 0;
  await pooled(jobs, 8, async (job) => {
    const target = join(IMAGES_DIR, job.file);
    let already = false;
    try {
      already = keepImages && statSync(target).size > 0;
    } catch {
      already = false;
    }
    if (!already) {
      writeFileSync(target, await shrink(await fetchImage(job.path)));
    }
    done += 1;
    if (done % 100 === 0) console.log(`  ${done}/${jobs.length}`);
  });

  const bytes = readdirSync(IMAGES_DIR).reduce(
    (total, file) => total + statSync(join(IMAGES_DIR, file)).size,
    0,
  );
  console.log(`  ${jobs.length} images, ${(bytes / 1e6).toFixed(1)} MB`);

  // --- catalogue ----------------------------------------------------------

  const catalogLines = entries.map((entry) => {
    const secondary = entry.secondaryMuscles.map((m) => `'${m}'`).join(', ');
    const equipment = entry.equipment === null ? 'null' : `'${entry.equipment}'`;
    return (
      `  {\n` +
      `    key: ${JSON.stringify(entry.key)},\n` +
      `    name: ${JSON.stringify(entry.name)},\n` +
      `    primaryMuscle: '${entry.primaryMuscle}',\n` +
      `    secondaryMuscles: [${secondary}],\n` +
      `    equipment: ${equipment},\n` +
      `    tracksDuration: ${entry.tracksDuration},\n` +
      `    hasImage: ${entry.imageFiles.length > 0},\n` +
      `    isDefault: ${entry.isDefault},\n` +
      `  },`
    );
  });

  writeFileSync(
    CATALOG_OUT,
    `${CATALOG_HEADER}\nexport const EXERCISE_CATALOG: readonly CatalogExercise[] = [\n${catalogLines.join(
      '\n',
    )}\n];\n`,
    'utf8',
  );
  console.log(`Wrote ${CATALOG_OUT}`);

  const imageLines = entries
    .filter((entry) => entry.imageFiles.length > 0)
    .map((entry) => {
      const requires = entry.imageFiles
        .map((file) => `require('../../../../assets/exercises/${file}') as number`)
        .join(', ');
      return `  ${JSON.stringify(entry.key)}: [${requires}],`;
    });

  writeFileSync(
    IMAGES_OUT,
    `${IMAGES_HEADER}\nexport const EXERCISE_IMAGES: Record<string, readonly number[]> = {\n${imageLines.join(
      '\n',
    )}\n};\n`,
    'utf8',
  );
  console.log(`Wrote ${IMAGES_OUT}`);

  writeFileSync(LICENCE_OUT, licence(entries.length, jobs.length), 'utf8');
  console.log(`Wrote ${LICENCE_OUT}`);
}

const CATALOG_HEADER = `// GENERATED by scripts/fetch-exercise-catalog.mjs. Do not edit.
//
// Exercise data and photographs from free-exercise-db
// (https://github.com/${REPO}), released under the Unlicense — a public-domain
// dedication. The notice travels with it in ./LICENSE.md, in this folder.
//
// The French names are this project's own; they are not from the source, which
// is English only. See scripts/exercise-names-fr.mjs.

import type { Equipment, Muscle } from '@/core/db/schema';

/** One catalogue entry, before it becomes an exercise. */
export interface CatalogExercise {
  /**
   * Stable key, and the media reference.
   *
   * It is what \`exercise.media_uri\` holds, prefixed — see MEDIA_SCHEME. Derived
   * from the French name, so it is readable in a database dump, and stable
   * because an archive exported today has to find its photographs in a binary
   * built next year.
   */
  key: string;
  name: string;
  primaryMuscle: Muscle;
  secondaryMuscles: Muscle[];
  /**
   * NULL means "not stated", which is a real answer rather than a gap.
   *
   * Slice 10 settled what it means: an exercise with no equipment matches NO
   * filter, because pretending it matches would assert something nobody said.
   */
  equipment: Equipment | null;
  /**
   * Measured in seconds rather than repetitions (slice 11).
   *
   * Stretches and cardio by category; holds, carries and isometrics by name.
   * This is the only thing that puts a non-zero value in
   * \`exercise.tracks_duration\` on a fresh installation.
   */
  tracksDuration: boolean;
  /** Whether EXERCISE_IMAGES has photographs for this key. Three entries do not. */
  hasImage: boolean;
  /**
   * Whether a brand-new library is given this one without being asked.
   *
   * The criterion is the SOURCE's category, not an opinion about what is
   * common — see DEFAULT_CATEGORIES in the generating script for why
   * \`level: 'beginner'\` was tried and rejected.
   */
  isDefault: boolean;
}
`;

