/**
 * The French name of every free-exercise-db exercise (specs 10.1).
 *
 * ## WHY THIS FILE EXISTS, WHICH IS THE COST OF THE SOURCE
 *
 * wger shipped its exercises ALREADY TRANSLATED by its contributors, and that
 * was a named benefit of choosing it. free-exercise-db is English only — 876
 * names, 583 distinct words — so switching sources means the translation
 * becomes ours. The alternative was an English library inside a French
 * application, which is a regression nobody asked for.
 *
 * ## IT IS A TABLE, NOT A RULE ENGINE, AND THAT IS DELIBERATE
 *
 * Exercise names look compositional — "Barbell Incline Bench Press" is four
 * parts — and a token translator handles maybe seven names in ten. The other
 * three are where it produces confident nonsense: French word order is not
 * English word order ("Développé couché à la barre", not "Barre couché
 * développé"), and the tail is idiomatic — "Conan's Wheel", "Spell Caster",
 * "Bradford Press", "Otis-Up". A wrong name in a library is not a broken
 * screen: it is a plausible label on the wrong movement, which is the only kind
 * of wrong this project treats as serious.
 *
 * So every name is written out. A key that is missing fails the build in
 * fetch-exercise-catalog.mjs rather than falling back to English silently.
 *
 * ## CONVENTIONS, SO THE TABLE DOES NOT DRIFT
 *
 * - equipment becomes a trailing complement: `à la barre`, `aux haltères`,
 *   `à la poulie`, `à la machine`, `au kettlebell`, `avec élastique`;
 * - `Bench Press` is `Développé couché`, `Row` is `Rowing`, `Pulldown` is
 *   `Tirage vertical`, `Deadlift` is `Soulevé de terre`, `Raise` is
 *   `Élévation`, `Flye` is `Écarté`, `Push-Up` is `Pompes`;
 * - the words French lifters actually use stay English: squat, curl, crunch,
 *   dips, hip thrust, good morning, leg curl, swing, thruster;
 * - `Stretch` is `Étirement`, `-SMR` is `Auto-massage` (self-myofascial
 *   release, which is a foam roller and nothing else).
 */

